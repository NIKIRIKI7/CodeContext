#[derive(Debug, Clone, Deserialize)]
struct LocalesBundleDto {
    ru: UiLabelsDto,
    en: UiLabelsDto,
}

static LOADED_LOCALES: OnceLock<(UiLabels, UiLabels)> = OnceLock::new();

fn loaded_locales() -> &'static (UiLabels, UiLabels) {
    LOADED_LOCALES.get_or_init(|| {
        let external_json = std::fs::read_to_string("assets/locales.json").ok();
        let raw_json = external_json.as_deref().unwrap_or(EMBEDDED_LOCALES_JSON);
        if let Ok(bundle) = serde_json::from_str::<LocalesBundleDto>(raw_json) {
            (bundle.ru.leak_to_static(), bundle.en.leak_to_static())
        } else if let Ok(bundle) = serde_json::from_str::<LocalesBundleDto>(EMBEDDED_LOCALES_JSON) {
            (bundle.ru.leak_to_static(), bundle.en.leak_to_static())
        } else {
            (UiLabels::default(), UiLabels::default())
        }
    })
}
