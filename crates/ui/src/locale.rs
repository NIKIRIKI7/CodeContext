pub const EMBEDDED_LOCALES_JSON: &str = include_str!("../../../assets/locales.json");

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum AppLocale {
    #[default]
    Ru,
    En,
}

impl AppLocale {
    #[inline]
    pub const fn language_id(self) -> LanguageIdentifier {
        match self {
            Self::Ru => langid!("ru-RU"),
            Self::En => langid!("en-US"),
        }
    }

    #[must_use]
    #[inline]
    pub const fn toggle(self) -> Self {
        match self {
            Self::Ru => Self::En,
            Self::En => Self::Ru,
        }
    }

    #[inline]
    pub const fn short_code(self) -> &'static str {
        match self {
            Self::Ru => "RU",
            Self::En => "EN",
        }
    }

    #[inline]
    pub fn labels(self) -> &'static UiLabels {
        let (ru_labels, en_labels) = loaded_locales();
        match self {
            Self::Ru => ru_labels,
            Self::En => en_labels,
        }
    }

    #[inline]
    pub fn toggle_state_label(self, enabled: bool) -> &'static str {
        let labels = self.labels();
        if enabled { labels.applier_backup_on } else { labels.applier_backup_off }
    }

    #[inline]
    pub fn hotkey_recording_label(self) -> &'static str {
        self.labels().hotkey_recording_prompt
    }
}

